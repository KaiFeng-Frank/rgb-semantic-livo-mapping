#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
write_arm_configs.py -- emit one config per arm, carrying the filter-E boundaries that
were RE-DERIVED ON seq 08.  The boundaries land in a file rather than on a command
line so that every arm's exact supervision rule is recoverable from the artefact.

Arms, exactly as the frozen design orders them:
  B1  freeze the backbone, train the head only.  Pseudo-labels, filter E, terrain and
      manmade excluded.  THE CHEAP KILL -- it runs first.
  D   GT supervision, IN-FRUSTUM ONLY.  Prices supervision sparsity.
  B0  pseudo-label distillation under filter E.  The main arm.
  C   GT supervision over ALL points.  The ceiling.
  R   GT supervision, a per-frame RANDOM subset the SAME SIZE as arm D's frustum.
      The control that separates supervision COUNT from frustum GEOMETRY.  It is not
      part of the serial stage-2 queue; run_v04_armR.sh runs it after stage 2 ends.
"""
import os, sys, json, argparse

HDR = '''"""AUTO-GENERATED by tools/write_arm_configs.py -- do not hand-edit.

Arm {arm}: {what}
filter E boundaries re-derived on seq {seq}: {spec}
"""
_base_ = ["./semseg-pt-v3m1-distil-common9.py"]
'''

ARMS = {
    "B1": dict(what="pseudo-labels, filter E, terrain/manmade excluded, BACKBONE FROZEN "
                    "(diagnostic: does classifier recalibration alone capture the gain?)",
               model=dict(freeze_backbone=True,
                          exclude_classes=("terrain", "manmade")),
               train=dict(label_source="pseudo", supervise="filterE")),
    "B0": dict(what="pseudo-label distillation under filter E (the main arm)",
               model=dict(freeze_backbone=False,
                          exclude_classes=("terrain", "manmade")),
               train=dict(label_source="pseudo", supervise="filterE")),
    "D": dict(what="GT supervision, IN-FRUSTUM ONLY (prices supervision sparsity)",
              model=dict(freeze_backbone=False, exclude_classes=()),
              train=dict(label_source="gt", supervise="frustum")),
    "C": dict(what="GT supervision over ALL points (the ceiling)",
              model=dict(freeze_backbone=False, exclude_classes=()),
              train=dict(label_source="gt", supervise="all")),
    "R": dict(what="GT supervision on a per-frame RANDOM subset matched point-for-point "
                   "in SIZE to arm D's frustum (separates supervision COUNT from "
                   "frustum GEOMETRY; identical to arm D except for that one field)",
              model=dict(freeze_backbone=False, exclude_classes=(),
                         kl_lambda=1.5305520007241327),
              note=("kl_lambda is PINNED to arm D's calibrated value, not calibrated at\n"
                    "step 0 like every other arm.  Arm R's only meaningful comparison is\n"
                    "against arm D, and the step-0 calibration is a one-batch gradient-norm\n"
                    "ratio that spans 0.441 / 0.969 / 1.531 across three runs of the SAME\n"
                    "full-fine-tune configuration (out/v04/lambda_calibration.jsonl) -- a\n"
                    "3.5x range on the anti-forgetting strength, against a +-0.60 mIoU\n"
                    "decision band.  Left free, arm R would differ from arm D in TWO\n"
                    "respects, supervision geometry AND anchor strength, and a two-factor\n"
                    "contrast attributes nothing.  This is deliberately DIFFERENT from how\n"
                    "B1 / B0 / C were handled and the reason is that those arms are not the\n"
                    "contrast arm R exists to make."),
              train=dict(label_source="gt", supervise="random")),
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--spec", required=True)
    ap.add_argument("--arms", default="", help="comma-separated subset of the arms; "
                    "empty (the default) writes them all, exactly as before")
    ap.add_argument("--dir", default="/data/wuyou/livo_sem/src/Pointcept_v151/configs/"
                                     "semantic_kitti")
    a = ap.parse_args()
    d = json.load(open(a.spec))
    spec = d["filter_spec"]
    seq = d.get("seq", "08")
    for arm in ([x for x in a.arms.split(",") if x] or list(ARMS)):
        c = ARMS[arm]
        p = os.path.join(a.dir, "arm_%s.py" % arm)
        with open(p, "w") as fh:
            fh.write(HDR.format(arm=arm, what=c["what"], seq=seq,
                                spec=json.dumps(spec)))
            fh.write("\nfilter_spec = %r\n" % (spec,))
            if c.get("note"):
                fh.write("\n" + "".join("# %s\n" % ln for ln in c["note"].split("\n")))
            fh.write("\nmodel = dict(\n")
            for k, v in c["model"].items():
                fh.write("    %s=%r,\n" % (k, v))
            fh.write(")\n")
            fh.write("\ndata = dict(train=dict(\n")
            for k, v in c["train"].items():
                fh.write("    %s=%r,\n" % (k, v))
            fh.write("    filter_spec=filter_spec,\n")
            fh.write("))\n")
        print("wrote %s" % p)


if __name__ == "__main__":
    main()
